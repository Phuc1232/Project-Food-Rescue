// AC-01..26: ApiContractTests responsibility.
package com.foodrescue.backend

import com.foodrescue.backend.support.AuthTestFixtures
import com.foodrescue.backend.common.security.validatePassword
import org.junit.jupiter.api.Test
import org.junit.jupiter.api.Assertions.*
class ApiContractTests: AuthTestFixtures() {
    @Test fun `validation malformed json security health and docs have correct contracts`() {
        val invalid=call("/api/v1/auth/register","POST",mapOf("email" to "","password" to "x","displayName" to ""))
        assertEquals(400,invalid.statusCode()); assertTrue(json(invalid)["fieldErrors"].size()>0)
        val malformed=call("/api/v1/auth/register","POST","{")
        assertEquals(400,malformed.statusCode()); assertTrue(json(malformed)["requestId"].asString().isNotBlank())
        val denied=call("/api/v1/accounts/me"); assertEquals(401,denied.statusCode())
        assertEquals(json(denied)["requestId"].asString(),denied.headers().firstValue("X-Request-ID").get())
        assertEquals(200,call("/actuator/health/liveness").statusCode()); assertEquals(200,call("/actuator/health/readiness").statusCode())
        assertFalse(call("/actuator/health/readiness").body().contains("components")); assertEquals(200,call("/openapi.yaml").statusCode())
        assertEquals(413,call("/api/v1/auth/register","POST","x".repeat(17000)).statusCode())
    }
    @Test fun `pagination only permits bounded sizes and whitelisted sort`() {
        register(); val access=login()["accessToken"].asString()
        for(q in listOf("size=101","page=-1","sort=passwordHash","page=abc"))
            assertEquals(400,call("/api/v1/auth/sessions?"+q,token=access).statusCode())
        assertEquals(400,call("/api/v1/auth/sessions/not-a-uuid","DELETE",token=access).statusCode())
        assertEquals(20,json(call("/api/v1/auth/sessions",token=access))["size"].asInt())
    }
    @Test fun `password policy counts Unicode code points without trimming`() {
        validatePassword("😀".repeat(12)); validatePassword(" ".repeat(12))
        assertThrows(Exception::class.java) { validatePassword("😀".repeat(11)) }
        assertThrows(Exception::class.java) { validatePassword("😀".repeat(129)) }
    }
    @Test fun `request id is generated by server and MDC cleared even on failure`() {
        val request=org.springframework.mock.web.MockHttpServletRequest(); request.addHeader("X-Request-ID","attacker-value")
        val response=org.springframework.mock.web.MockHttpServletResponse()
        val filter=com.foodrescue.backend.middleware.request.RequestIdFilter()
        assertThrows(jakarta.servlet.ServletException::class.java) {
            filter.doFilter(request,response,jakarta.servlet.FilterChain { _,_ ->
                assertEquals(response.getHeader("X-Request-ID"),org.slf4j.MDC.get("requestId"))
                throw jakarta.servlet.ServletException("simulated failure")
            })
        }
        assertNotEquals("attacker-value",response.getHeader("X-Request-ID")); assertNull(org.slf4j.MDC.get("requestId"))
    }

}

// The same HTTP assertions run with the actual production route policy.
@org.springframework.test.context.ActiveProfiles(profiles=["prod"],inheritProfiles=false)
class ProductionApiContractTests: AuthTestFixtures() {
    @Test fun `production hides docs and health details`() {
        for(path in listOf("/docs","/openapi.yaml","/actuator/env")) assertEquals(401,call(path).statusCode())
        val health=call("/actuator/health/readiness")
        assertEquals(200,health.statusCode()); assertFalse(health.body().contains("components"))
    }
}
